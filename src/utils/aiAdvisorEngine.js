function normalizeQuery(str = "") {
  return String(str)
    .toLowerCase()
    .replace(/[أإآءئ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/[\u064B-\u065F]/g, "")
    .replace(/[-_/:,.;()&"'+]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

